/* -------------------------------
   ROTATING REVIEWS
--------------------------------*/

reviewGroups.forEach((group, boxIndex)=>{

    const slider=document.getElementById(`review${boxIndex}`);

    let current=0;

    function showReview(){

        slider.classList.add("slide-out");

        setTimeout(()=>{

            const review=group[current];

            slider.innerHTML=`

            <div class="review-item">

                <div class="stars">${review.stars}</div>

                <p>"${review.text}"</p>

                <h5>${review.name}</h5>

            </div>

            `;

            slider.classList.remove("slide-out");

            slider.classList.add("slide-up");

            setTimeout(()=>{

                slider.classList.remove("slide-up");

            },700);

            current=(current+1)%group.length;

        },700);

    }

    showReview();

    let interval=setInterval(showReview,8000);

    slider.parentElement.addEventListener("mouseenter",()=>{

        clearInterval(interval);

    });

    slider.parentElement.addEventListener("mouseleave",()=>{

        interval=setInterval(showReview,8000);

    });

});